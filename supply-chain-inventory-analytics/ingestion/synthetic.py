FX_TO_USD = {"USD": 1.0, "EUR": 1.08, "GBP": 1.27}


@dataclass
class _Line:
    supplier_id: str
    sku: str
    location_id: str
    order_date: date
    approval_date: date
    promised_date: date
    qty_ea: int
    unit_cost_usd: float
    cancelled: bool
    receipts: list = field(default_factory=list)  # (date, received_ea, accepted_ea)

    def remaining(self, upto: date) -> int:
        if self.cancelled:
            return 0
        got = sum(r[1] for r in self.receipts if r[0] <= upto)
        planned = sum(r[1] for r in self.receipts)
        # remaining qty still expected from the supplier (short-closed lines expect nothing more)
        return max(planned - got, 0)


def _products(rng: np.random.Generator, n_skus: int) -> pd.DataFrame:
    rows = []
    cats = list(CATEGORIES)
    for i in range(n_skus):
        cat = cats[i % len(cats)]
        name = CATEGORIES[cat][(i // len(cats)) % len(CATEGORIES[cat])]
        cat_suppliers = SUPPLIERS[SUPPLIERS["category"] == cat]["supplier_id"].tolist()
        rows.append({
            "sku": f"SKU-{1001 + i}",
            "product_name": name,
            "category": cat,
            "base_uom": "EA",
            "case_pack": int(rng.choice([6, 12, 24, 50])),
            "unit_cost_usd": round(float(np.exp(rng.normal(2.6, 1.0))), 2),
            "primary_supplier_id": cat_suppliers[i % len(cat_suppliers)],
        })
    df = pd.DataFrame(rows)
    df["moq_units"] = df["case_pack"] * rng.choice([1, 2, 4], size=len(df))
    return df


def generate(raw_dir: str | Path, as_of: date, seed: int = 42, n_skus: int = 40, days: int = 548,
             inject_defects: bool = True) -> dict[str, pd.DataFrame]:
    """Simulate the network and write source-shaped CSV extracts to raw_dir."""
    rng = np.random.default_rng(seed)
    raw_dir = Path(raw_dir)
    raw_dir.mkdir(parents=True, exist_ok=True)
    start = as_of - timedelta(days=days - 1)
    dates = [start + timedelta(days=d) for d in range(days)]
    doy = np.array([d.timetuple().tm_yday for d in dates])
    weekday = np.array([d.weekday() for d in dates])

    products = _products(rng, n_skus)
    sup = SUPPLIERS.set_index("supplier_id")

    # --- product demand profiles -------------------------------------------------
    order = rng.permutation(n_skus)
    base = 400.0 * (order + 1.0) ** -1.25          # Pareto-like spread => meaningful ABC classes
    profile = np.array(["regular"] * n_skus, dtype=object)
    idx = rng.permutation(np.flatnonzero(order >= 4))      # keep the 4 highest-volume SKUs as regular items
    profile[idx[:6]] = "intermittent"
    profile[idx[6:8]] = "new"
    profile[idx[8:10]] = "phase_out"
    policy = np.ones(n_skus)
    policy[idx[10:14]] = 0.45                      # under-buffered => stockouts
    policy[idx[14:18]] = 2.6                       # over-buffered => excess
    products["lifecycle_status"] = np.where(profile == "new", "New",
                                            np.where(profile == "phase_out", "Phase-out", "Active"))
    launch_day = np.where(profile == "new", rng.integers(days // 2, days * 2 // 3, n_skus), 0)
    products["launch_date"] = [dates[int(d)] for d in launch_day]
    products["demand_profile"] = profile  # dropped before writing; kept for documentation tests

    amp = rng.uniform(0.05, 0.35, n_skus)
    phase = rng.integers(0, 365, n_skus)
    trend = rng.normal(0.05, 0.10, n_skus)
    wk_factor = np.where(weekday < 5, 1.18, 0.55)
    volatility = rng.uniform(0.08, 0.85, n_skus)          # week-to-week demand shocks (drives XYZ)
    week_idx = np.arange(days) // 7

    snaps, moves, demand, lines = [], [], [], []
    move_seq = 0
    # state keyed by (sku_idx, loc_idx)
    on_hand = {}
    for p in range(n_skus):
        for li, loc in LOCATIONS.iterrows():
            on_hand[(p, li)] = 0

    # pre-compute daily demand arrays
    lam = {}
    for p in range(n_skus):
        t = np.arange(days) / 365.0
        season = 1 + amp[p] * np.sin(2 * np.pi * (doy - phase[p]) / 365.0)
        level = base[p] * season * wk_factor * (1 + trend[p] * t)
        level = level * np.exp(rng.normal(0, volatility[p], week_idx[-1] + 1))[week_idx]
        if profile[p] == "phase_out":
            level = level * np.clip(1 - np.arange(days) / (days * 0.75), 0.05, 1)
        if profile[p] == "new":
            level = np.where(np.arange(days) >= launch_day[p], level, 0.0)
        lam[p] = np.clip(level, 0, None)

    open_lines: dict[tuple[int, int], list[_Line]] = {k: [] for k in on_hand}
    req_arr = {}
    for p in range(n_skus):
        for li, loc in LOCATIONS.iterrows():
            l = lam[p] * loc["demand_share"]
            if profile[p] == "intermittent":
                occurs = rng.random(days) < np.clip(l / 12.0, 0, 0.25)
                req = np.where(occurs, rng.poisson(11.0, days) + 1, 0)
            else:
                req = rng.poisson(l)
            req_arr[(p, li)] = req

    # policy parameters from *nominal* assumptions (planner's static settings)
    params = {}
    for p in range(n_skus):
        s_row = sup.loc[products.at[p, "primary_supplier_id"]]
        lt = s_row["nominal_lead_time_days"]
        for li, loc in LOCATIONS.iterrows():
            d = max(float(np.mean(lam[p][launch_day[p]:launch_day[p] + 120])) * loc["demand_share"], 0.05)
            weekly = req_arr[(p, li)][:126].reshape(18, 7).sum(axis=1)
            sigma_w = max(float(np.std(weekly)), 1.0)       # weekly shocks are autocorrelated within a week
            ss = 2.0 * sigma_w * np.sqrt(lt / 7.0) * policy[p]
            s_level = d * lt * min(policy[p], 1.3) + ss
            big_s = s_level + d * 21 * policy[p]
            params[(p, li)] = (s_level, big_s)
            init = (s_level + big_s) / 2                      # start mid-cycle to avoid a warm-up spike
            if profile[p] == "new":
                init = 0
            on_hand[(p, li)] = int(round(init))

    sku_l = products["sku"].tolist()
    pack_l = products["case_pack"].astype(int).tolist()
    moq_l = products["moq_units"].astype(int).tolist()
    cost_l = products["unit_cost_usd"].astype(float).tolist()
    supp_l = [dict(SUPPLIERS.set_index("supplier_id").loc[s].to_dict(), supplier_id=s)
              for s in products["primary_supplier_id"]]
    loc_l = LOCATIONS["location_id"].tolist()
    share_l = LOCATIONS["demand_share"].astype(float).tolist()
    phase_out_stop = int(days * 0.55)
    n_locs = len(LOCATIONS)

    def add_move(day: date, p: int, li: int, mtype: str, qty: int, ref: str, uom: str = "EA") -> None:
        nonlocal move_seq
        move_seq += 1
        secs = int(rng.integers(6 * 3600, 22 * 3600))
        moves.append((f"MV-{move_seq:08d}", datetime.combine(day, time()) + timedelta(seconds=secs),
                      sku_l[p], loc_l[li], mtype, qty, uom, ref))

    for di, day in enumerate(dates):
        for p in range(n_skus):
            sku = sku_l[p]
            for li in range(n_locs):
                key = (p, li)
                # 1. receipts due today
                for ln in open_lines[key]:
                    for r in ln.receipts:
                        if r[0] == day and r[2] > 0:
                            on_hand[key] += r[2]
                            add_move(day, p, li, "RECEIPT", r[2], f"GRN:{id(ln)}")
                # 2. demand
                req = int(req_arr[key][di])
                fulfilled = min(req, max(on_hand[key], 0))
                on_hand[key] -= fulfilled
                demand.append((day, sku, loc_l[li], req, fulfilled, req - fulfilled))
                if fulfilled:
                    add_move(day, p, li, "ISSUE", -fulfilled, f"SO-{day:%Y%m%d}-{p:03d}{li}")
                # 3. occasional cycle-count adjustment
                if rng.random() < 0.006 and on_hand[key] > 10:
                    adj = int(rng.integers(-4, 3)) or -1
                    on_hand[key] += adj
                    add_move(day, p, li, "ADJUSTMENT", adj, f"CC-{day:%Y%m%d}")
            # 4. weekly transfers between locations for the same SKU (instant, documented simplification)
            if day.weekday() == 0:
                d_loc = [max(lam[p][di] * share_l[li], 0.01) for li in range(n_locs)]
                cover = [on_hand[(p, li)] / d_loc[li] for li in range(n_locs)]
                src, dst = int(np.argmax(cover)), int(np.argmin(cover))
                if cover[src] > 60 and cover[dst] < 5 and src != dst:
                    q = int(min(on_hand[(p, src)] * 0.3, d_loc[dst] * 21))
                    if q > 0:
                        ref = f"TR-{day:%Y%m%d}-{p:03d}"
                        on_hand[(p, src)] -= q
                        on_hand[(p, dst)] += q
                        add_move(day, p, src, "TRANSFER_OUT", -q, ref)
                        add_move(day, p, dst, "TRANSFER_IN", q, ref)
            # 5. reorder review + 6. end-of-day snapshot
            s_row = supp_l[p]
            for li in range(n_locs):
                key = (p, li)
                s_level, big_s = params[key]
                on_order = sum(ln.remaining(day) for ln in open_lines[key])
                can_order = not (profile[p] == "phase_out" and di > phase_out_stop) and \
                    not (profile[p] == "new" and di < launch_day[p] - 20)
                if can_order and on_hand[key] + on_order <= s_level:
                    pack = int(pack_l[p])
                    qty = max(big_s - on_hand[key] - on_order, moq_l[p])
                    qty = int(np.ceil(qty / pack) * pack)
                    approval = day + timedelta(days=int(rng.integers(0, 3)))
                    nominal = int(s_row["nominal_lead_time_days"])
                    cancelled = rng.random() < 0.02
                    ln = _Line(s_row["supplier_id"], sku_l[p], loc_l[li], day,
                               approval, approval + timedelta(days=nominal + int(round(s_row["lt_std"]))), qty,
                               float(cost_l[p]) * float(rng.normal(1.0, 0.04)), cancelled)
                    if not cancelled:
                        actual = max(2, int(round(rng.normal(nominal + s_row["lt_bias"], s_row["lt_std"]))))
                        first = approval + timedelta(days=actual)
                        delivered = qty
                        if rng.random() < s_row["p_short"]:
                            delivered = int(qty * rng.uniform(0.85, 0.97))
                        if rng.random() < s_row["p_partial"]:
                            q1 = int(delivered * rng.uniform(0.5, 0.8))
                            parts = [(first, q1), (first + timedelta(days=int(rng.integers(3, 11))), delivered - q1)]
                        else:
                            parts = [(first, delivered)]
                        for rd, rq in parts:
                            rej = int(rq * rng.uniform(0.01, 0.06)) if rng.random() < s_row["defect_rate"] * 6 else 0
                            ln.receipts.append((rd, rq, rq - rej))
                    open_lines[key].append(ln)
                    lines.append(ln)
                transit_cut = day + timedelta(days=3)
                in_transit = sum(r[1] for ln in open_lines[key] if not ln.cancelled
                                 for r in ln.receipts if day < r[0] <= transit_cut)
                oh = on_hand[key]
                reserved = int(min(max(oh, 0), rng.poisson(max(lam[p][di] * share_l[li] * 0.3, 0.01))))
                snaps.append((datetime.combine(day, time(23, 59, 59)), sku_l[p],
                              loc_l[li], oh, reserved, in_transit))
            # prune fully received lines from the open list
            for li in range(n_locs):
                open_lines[(p, li)] = [ln for ln in open_lines[(p, li)]
                                       if not ln.cancelled and any(r[0] > day for r in ln.receipts)]

    # --- assemble source extracts --------------------------------------------------
    snap_df = pd.DataFrame(snaps, columns=["snapshot_ts", "sku", "location_id", "on_hand_qty", "reserved_qty",
                                           "in_transit_qty"])
    snap_df["uom"] = "EA"
    move_df = pd.DataFrame(moves, columns=["movement_id", "movement_ts", "sku", "location_id", "movement_type",
                                           "quantity", "uom", "reference"])
    dem_df = pd.DataFrame(demand, columns=["demand_date", "sku", "location_id", "requested_qty", "fulfilled_qty",
                                           "backordered_qty"])
    dem_df["uom"] = "EA"

    # POs: group lines raised for the same supplier/location/day into one PO document
    po_rows, rc_rows = [], []
    line_df = pd.DataFrame([{"k": i, "supplier_id": ln.supplier_id, "location_id": ln.location_id,
                             "order_date": ln.order_date} for i, ln in enumerate(lines)])
    grp = line_df.groupby(["supplier_id", "location_id", "order_date"], sort=True).ngroup()
    line_df["po_number"] = [f"PO-{g + 100001}" for g in grp]
    line_df["po_line"] = line_df.groupby("po_number").cumcount() + 1
    grn_map = {}
    rc_seq = 0
    for row in line_df.itertuples():
        ln = lines[row.k]
        s_row = sup.loc[ln.supplier_id]
        uom = s_row["order_uom"]
        pack = int(products.loc[products["sku"] == ln.sku, "case_pack"].iloc[0])
        factor = pack if uom == "CS" else 1
        fx = FX_TO_USD[s_row["currency"]]
        recorded = [r for r in ln.receipts if r[0] <= as_of]
        if ln.cancelled:
            status = "Cancelled"
        elif not recorded:
            status = "Open"
        elif len(recorded) == len(ln.receipts):
            status = "Closed"
        else:
            status = "Partially Received"
        po_rows.append((row.po_number, row.po_line, ln.supplier_id, ln.sku, ln.location_id, ln.order_date,
                        ln.approval_date, ln.promised_date, ln.qty_ea // factor if uom == "CS" else ln.qty_ea,
                        uom, round(ln.unit_cost_usd * factor / fx, 4), s_row["currency"], status))
        for rd, rq, acc in recorded:
            rc_seq += 1
            rid = f"GRN-{rc_seq:07d}"
            grn_map[(id(ln), rd)] = (rid, row.po_number, row.po_line)
            rej = rq - acc
            outcome = "Pass" if rej == 0 else ("Fail" if rej > rq * 0.5 else "Partial reject")
            ts = datetime.combine(rd, time()) + timedelta(seconds=int(rng.integers(7 * 3600, 17 * 3600)))
            if uom == "CS" and rq % factor == 0 and acc % factor == 0:  # whole cases => recorded in CS
                rc_rows.append((rid, row.po_number, row.po_line, ts, rq / factor, acc / factor, rej / factor, "CS",
                                outcome))
            else:
                rc_rows.append((rid, row.po_number, row.po_line, ts, rq, acc, rej, "EA", outcome))
    po_df = pd.DataFrame(po_rows, columns=["po_number", "po_line", "supplier_id", "sku", "location_id",
                                           "order_date", "approval_date", "promised_date", "ordered_qty", "uom",
                                           "unit_cost", "currency", "status"])
    rc_df = pd.DataFrame(rc_rows, columns=["receipt_id", "po_number", "po_line", "receipt_ts", "received_qty",
                                           "accepted_qty", "rejected_qty", "uom", "inspection_outcome"])
    # receipt movements reference the GRN document; express them in the supplier's order UoM
    ref_lookup = {}
    for ln in lines:
        for rd, rq, acc in ln.receipts:
            if (id(ln), rd) in grn_map:
                ref_lookup[f"GRN:{id(ln)}"] = ref_lookup.get(f"GRN:{id(ln)}", []) + [(rd, grn_map[(id(ln), rd)][0])]
    def _ref(r):
        if not r.reference.startswith("GRN:"):
            return r.reference
        for rd, rid in ref_lookup.get(r.reference, []):
            if rd == r.movement_ts.date():
                return rid
        return r.reference
    move_df["reference"] = [_ref(r) for r in move_df.itertuples()]
    # cases supplier receipts: movements recorded in CS where divisible (mixed UoM in the WMS extract)
    pack_map = products.set_index("sku")["case_pack"]
    is_rcpt = move_df["movement_type"].eq("RECEIPT")
    packs = move_df["sku"].map(pack_map)
    to_cs = is_rcpt & (move_df["quantity"] % packs == 0) & (move_df.index % 2 == 0)
    move_df.loc[to_cs, "quantity"] = (move_df.loc[to_cs, "quantity"] // packs[to_cs]).astype(int)
    move_df.loc[to_cs, "uom"] = "CS"

    if inject_defects:
        # duplicates (exact re-sent rows)
        move_df = pd.concat([move_df, move_df.sample(5, random_state=seed)], ignore_index=True)
        dem_df = pd.concat([dem_df, dem_df.sample(3, random_state=seed)], ignore_index=True)
        rc_df = pd.concat([rc_df, rc_df.sample(2, random_state=seed)], ignore_index=True)
        # negative on-hand keyed in error on one snapshot row
        cand = snap_df.index[(snap_df["on_hand_qty"] > 20) & (snap_df["location_id"] == "DC-STH")
                             & (snap_df["snapshot_ts"].dt.date < as_of - timedelta(days=30))]
        bad = cand[len(cand) // 2]
        snap_df.loc[bad, "on_hand_qty"] = -int(snap_df.loc[bad, "on_hand_qty"])
        # orphan keys
        orphan_po = po_df.sample(2, random_state=seed).assign(supplier_id="SUP-099", po_line=99)
        po_df = pd.concat([po_df, orphan_po], ignore_index=True)
        dem_df = pd.concat([dem_df, pd.DataFrame([(as_of, "SKU-9999", "DC-NTH", 5, 5, 0, "EA")],
                                                 columns=dem_df.columns)], ignore_index=True)
        move_df = pd.concat([move_df, pd.DataFrame([("MV-99999999", datetime.combine(as_of, time(12)), "SKU-1001",
                                                     "LOC-99", "ISSUE", -3, "EA", "SO-UNKNOWN")],
                                                   columns=move_df.columns)], ignore_index=True)
        # stale feed: eastern hub snapshots stop three days early
        stale = (snap_df["location_id"] == "HUB-EST") & (snap_df["snapshot_ts"].dt.date > as_of - timedelta(days=3))
        snap_df = snap_df[~stale]

    out = {
        "products": products.drop(columns=["demand_profile"]),
        "suppliers": SUPPLIERS[["supplier_id", "supplier_name", "region", "country", "currency",
                                "payment_terms_days", "approved_status", "category", "nominal_lead_time_days"]],
        "locations": LOCATIONS.drop(columns=["demand_share"]),
        "inventory_snapshots": snap_df,
        "inventory_movements": move_df,
        "demand": dem_df,
        "purchase_orders": po_df,
        "receipts": rc_df,
    }
    for name, df in out.items():
        df.to_csv(raw_dir / f"{name}.csv", index=False)
    return out


