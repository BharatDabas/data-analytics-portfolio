"""Deterministic synthetic data generator for the supply chain demo.

ALL DATA PRODUCED HERE IS SYNTHETIC. It is generated by simulating a simple
(s, S) replenishment policy over a small distribution network so that every
source extract is internally consistent: inventory snapshots equal opening
stock plus stock movements, receipts belong to purchase-order lines, and
demand fulfilment is limited by the stock that was actually on hand.

A handful of deliberate data-quality defects are injected so that the
validation layer has something real to detect (see docs/sample_data.md):
duplicate rows, a negative on-hand snapshot, orphan supplier / product /
location keys, mixed units of measure (cases vs each), supplier prices in
EUR/GBP, and one location whose snapshot feed stops early (stale snapshots).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date, datetime, time, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

